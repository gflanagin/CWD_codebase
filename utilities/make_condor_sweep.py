"""Turn a folder of sweep points into an HTCondor DAG.

    python utilities/make_condor_sweep.py --mesh BUNDLE --params sweep_params \\
        --outroot /shared/runs/grid --submit-dir condor/grid
    condor_submit_dag condor/grid/sweep.dag

The DAG runs one baseline node alone first (warming the FFCx JIT cache), then
one baseline per spin-up group, then each group's points as children of its
baseline, so the group's cached disease spin-up is computed once.

Assumes a shared filesystem: the submit files set should_transfer_files = NO
and getenv = False, and every path in them is absolute.
"""
import argparse
import io
import json
import re
from pathlib import Path

# Characters DAGMan does not accept in node names.
NODE_SAFE = re.compile(r"[^A-Za-z0-9_.-]")


def node_name(prefix, name):
    return "%s_%s" % (prefix, NODE_SAFE.sub("_", name))


def group_of(point):
    """The spin-up group: everything before the first '__' (see sweep_setup.py)."""
    return point.split("__", 1)[0]


def read_manifest(params):
    path = params / "manifest.txt"
    if not path.is_file():
        raise SystemExit("no manifest.txt in %s -- run sweep_setup.py first"
                         % params)
    points = [ln.strip() for ln in io.open(path, encoding="utf-8")
              if ln.strip()]
    if not points:
        raise SystemExit("%s is empty" % path)
    missing = [p for p in points if not (params / (p + ".json")).is_file()]
    if missing:
        raise SystemExit("manifest names %d point(s) with no .json: %s"
                         % (len(missing), ", ".join(missing[:5])))
    return points


def size_estimate(equilibrium, sample_point):
    """Per-job trajectory (scratch) and L-BFGS-B (memory) sizes, in GiB."""
    try:
        import numpy as np
    except ImportError:
        return None
    if not equilibrium.is_file():
        return None
    nodes = int(np.load(equilibrium, mmap_mode="r").size)
    p = json.loads(io.open(sample_point, encoding="utf-8").read())
    steps = round(p["time"]["final_time_years"] / p["time"]["time_step_years"])
    blocks = round(p["time"]["final_time_years"]
                   / p["optimal_control"]["control_block_years"])
    memory = int(p["optimal_control"]["lbfgs_memory"])
    gib = float(2 ** 30)
    control = blocks * nodes * 8
    return {
        "nodes": nodes,
        "steps": steps,
        "blocks": blocks,
        "trajectory_gib": (steps + 1) * nodes * 5 * 8 / gib,
        "work_gib": (2 * memory + 5) * control / gib,
    }


SUBMIT = """\
# Generated by utilities/make_condor_sweep.py -- edit the generator, not this.
universe                = vanilla
executable              = {runner}
initialdir              = {repo}
environment             = "CWD_SWEEP_ENV={env}"

# Shared filesystem; the job's environment comes from the file above.
should_transfer_files   = NO
getenv                  = False

request_cpus            = 1
request_memory          = {memory}
request_disk            = {disk}

output                  = {logdir}/{prefix}_$(name).out
error                   = {logdir}/{prefix}_$(name).err
log                     = {logdir}/sweep.log
notification            = Never

# Release held jobs automatically, up to three starts.
periodic_release        = (NumJobStarts < 3) && ((CurrentTime - EnteredCurrentStatus) > 600)
{extra}
arguments               = "{mode} $(name) $(group)"
queue
"""


def main():
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mesh", required=True,
                    help="Mesh bundle folder, visible on the execute nodes.")
    ap.add_argument("--params", required=True,
                    help="Folder of per-point .json files plus manifest.txt, "
                         "as written by sweep_setup.py.")
    ap.add_argument("--outroot", required=True,
                    help="Where results go. One folder per point, plus "
                         "baseline_<group>/ and spinup_cache/. Put this on a "
                         "filesystem with room for the whole sweep.")
    ap.add_argument("--submit-dir", required=True,
                    help="Where the DAG, the submit files and the per-job "
                         "logs are written.")
    ap.add_argument("--python",
                    default="/opt/conda/envs/cwd-fem/bin/python",
                    help="Interpreter on the execute nodes (default: "
                         "%(default)s). Its bin/ is prepended to PATH so FFCx "
                         "can find the conda gcc.")
    ap.add_argument("--driver", default="CWD_optimal_control.py",
                    help="Driver script, relative to the repo root.")
    ap.add_argument("--request-memory", default=None,
                    help="request_memory for a point job, e.g. 6G. Default is "
                         "the estimated optimizer workspace plus 2 GiB. Raise "
                         "it if the pool counts page cache of memory-mapped "
                         "files against the job.")
    ap.add_argument("--request-disk", default=None,
                    help="request_disk for a point job, e.g. 12G. Default is "
                         "twice the trajectory memmap.")
    ap.add_argument("--susceptible-equilibrium", default=None,
                    help="Cached disease-free field to use instead of the "
                         "bundle's own susceptible_equilibrium.npy; added to "
                         "every job's command line.")
    ap.add_argument("--extra-args",
                    default="--checkpoint-every 10 "
                            "--output-every 40 --no-spinup-series",
                    help="Driver flags common to every controlled point.")
    ap.add_argument("--retry", type=int, default=2,
                    help="DAGMan retries per node (default: %(default)s). "
                         "Completed nodes are skipped.")
    ap.add_argument("--max-jobs", type=int, default=None,
                    help="Write a DAGMan MAXJOBS throttle. Omit to let the "
                         "pool schedule everything at once.")
    ap.add_argument("--accounting-group", default=None,
                    help="Value for accounting_group in every submit file, if "
                         "the pool requires one.")
    ap.add_argument("--requirements", default=None,
                    help="Extra ClassAd requirements expression.")
    args = ap.parse_args()

    repo = Path(__file__).resolve().parent.parent
    mesh = Path(args.mesh).expanduser().resolve()
    params = Path(args.params).expanduser().resolve()
    outroot = Path(args.outroot).expanduser()
    submit = Path(args.submit_dir).expanduser().resolve()

    # HTCondor submit files cannot quote paths containing whitespace.
    spaced = [(label, p) for label, p in
              (("repo", repo), ("mesh", mesh), ("params", params),
               ("outroot", outroot), ("submit-dir", submit))
              if any(ch.isspace() for ch in str(p))]
    if spaced:
        raise SystemExit(
            "HTCondor cannot be given these paths, because they contain "
            "whitespace:\n"
            + "\n".join("  %-11s %s" % (label, p) for label, p in spaced)
            + "\n  Use whitespace-free paths on the cluster.")

    if not mesh.is_dir():
        raise SystemExit("no such mesh folder: %s" % mesh)
    # A missing equilibrium is computed by the warm baseline, which runs alone.
    eq = (Path(args.susceptible_equilibrium) if args.susceptible_equilibrium
          else mesh / "susceptible_equilibrium.npy")
    if not eq.is_file():
        print("note: %s is missing; the warm baseline computes it.\n"
              "  No size estimate without it: set --request-memory and "
              "--request-disk." % eq)
    # Carry the override onto every job, unless it is already in --extra-args.
    if (args.susceptible_equilibrium
            and "--susceptible-equilibrium" not in args.extra_args):
        args.extra_args = (args.extra_args
                           + " --susceptible-equilibrium " + str(eq))

    points = read_manifest(params)
    groups = sorted({group_of(p) for p in points})
    by_group = {g: [p for p in points if group_of(p) == g] for g in groups}

    logdir = submit / "logs"
    logdir.mkdir(parents=True, exist_ok=True)

    est = size_estimate(eq, params / (points[0] + ".json"))
    if args.request_memory:
        memory = args.request_memory
    elif est:
        memory = "%dM" % int(est["work_gib"] * 1024 + 2048)
    else:
        memory = "6G"
    if args.request_disk:
        disk = args.request_disk
    elif est:
        disk = "%dM" % int(est["trajectory_gib"] * 1024 * 2 + 1024)
    else:
        disk = "12G"

    extra_lines = []
    if args.accounting_group:
        extra_lines.append("accounting_group        = %s"
                           % args.accounting_group)
    if args.requirements:
        extra_lines.append("requirements            = %s" % args.requirements)
    extra = ("\n".join(extra_lines) + "\n") if extra_lines else ""

    env_path = submit / "sweep.env"
    runner = repo / "condor" / "run_solve.sh"
    common = dict(runner=runner, repo=repo, env=env_path, logdir=logdir,
                  extra=extra)

    io.open(submit / "point.sub", "w", encoding="utf-8", newline="\n").write(
        SUBMIT.format(mode="point", prefix="pt", memory=memory, disk=disk,
                      **common))
    # A baseline is one forward solve with no stored trajectory.
    io.open(submit / "baseline.sub", "w", encoding="utf-8",
            newline="\n").write(
        SUBMIT.format(mode="baseline", prefix="base", memory="4G", disk="4G",
                      **common))

    io.open(env_path, "w", encoding="utf-8", newline="\n").write(
        "# Generated by utilities/make_condor_sweep.py. Sourced by\n"
        "# condor/run_solve.sh inside every job.\n"
        "export CWD_PYTHON=%s\n"
        "export CWD_REPO=%s\n"
        "export CWD_DRIVER=%s\n"
        "export CWD_MESH=%s\n"
        "export CWD_PARAMS=%s\n"
        "export CWD_OUTROOT=%s\n"
        "export CWD_JIT_CACHE=%s\n"
        "export CWD_EXTRA_ARGS=%s\n"
        % (args.python, repo, args.driver, mesh, params, outroot,
           outroot / ".cache", json.dumps(args.extra_args)))

    warm = groups[0]
    lines = [
        "# HTCondor DAG for %d point(s) in %d spin-up group(s)."
        % (len(points), len(groups)),
        "# Generated by utilities/make_condor_sweep.py; regenerate rather than",
        "# edit. Submit with: condor_submit_dag %s" % (submit / "sweep.dag"),
        "",
    ]
    if args.max_jobs:
        lines += ["MAXJOBS point %d" % args.max_jobs, ""]

    lines += [
        "# The warm node runs alone so FFCx compiles every form into the",
        "# shared JIT cache before anything runs concurrently against it.",
        "JOB %s %s" % (node_name("base", warm), submit / "baseline.sub"),
        'VARS %s name="%s" group="%s"'
        % (node_name("base", warm), by_group[warm][0], warm),
        "RETRY %s %d" % (node_name("base", warm), args.retry),
        "",
    ]

    for g in groups[1:]:
        n = node_name("base", g)
        lines += [
            "JOB %s %s" % (n, submit / "baseline.sub"),
            'VARS %s name="%s" group="%s"' % (n, by_group[g][0], g),
            "RETRY %s %d" % (n, args.retry),
            "PARENT %s CHILD %s" % (node_name("base", warm), n),
            "",
        ]

    for g in groups:
        for p in by_group[g]:
            n = node_name("pt", p)
            lines += [
                # CATEGORY must be its own DAG line, not part of JOB.
                "JOB %s %s" % (n, submit / "point.sub"),
                "CATEGORY %s point" % n,
                'VARS %s name="%s" group="%s"' % (n, p, g),
                "RETRY %s %d" % (n, args.retry),
                "PARENT %s CHILD %s" % (node_name("base", g), n),
            ]
        lines.append("")

    io.open(submit / "sweep.dag", "w", encoding="utf-8", newline="\n").write(
        "\n".join(lines) + "\n")

    print("points          : %d in %d spin-up group(s)"
          % (len(points), len(groups)))
    for g in groups:
        print("  %-40s %d point(s)" % (g, len(by_group[g])))
    if est:
        print()
        print("  nodes %s   steps %d   blocks %d"
              % (format(est["nodes"], ","), est["steps"], est["blocks"]))
        print("  trajectory  %6.2f GiB per point (execute-node scratch)"
              % est["trajectory_gib"])
        print("  L-BFGS-B    %6.2f GiB per point (resident)"
              % est["work_gib"])
    print()
    print("request_memory  : %s" % memory)
    print("request_disk    : %s" % disk)
    print("outroot         : %s" % outroot)
    print("submit dir      : %s" % submit)
    print()
    print("submit with:")
    print("  condor_submit_dag %s" % (submit / "sweep.dag"))
    print("then watch with:")
    print("  condor_q -dag; tail -f %s.dagman.out" % (submit / "sweep.dag"))
    print("summarize with:")
    print("  %s utilities/sweep_report.py %s" % (args.python, outroot))


if __name__ == "__main__":
    main()
